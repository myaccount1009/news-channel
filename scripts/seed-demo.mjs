const { data: cats, error: catErr } = await supa.from('categories').select('id,slug');
if (catErr || !cats?.length) {
  console.error('❌ categories টেবিল পাওয়া যায়নি। আগে supabase/schema.sql চালান।', catErr?.message ?? '');
  process.exit(1);
}
const catId = Object.fromEntries(cats.map((c) => [c.slug, c.id]));

const prefix = 'https://demo.example/seed/';
const { data: existing } = await supa.from('posts').select('source_url').like('source_url', `${prefix}%`);
const have = new Set((existing ?? []).map((r) => r.source_url));

const now = Date.now();
const rows = [];
NEWS.forEach(([slug, title, excerpt, tags], i) => {
  const source_url = `${prefix}${i + 1}`;
  if (have.has(source_url) || !catId[slug]) return;
  const body = [excerpt, ...FILLER].map((t) => `<p>${t}</p>`).join('\n');
  rows.push({
    title,
    slug: `demo-news-${i + 1}`,
    excerpt,
    content: body,
    image_url: `https://picsum.photos/seed/portal${i + 1}/1200/675`,
    image_alt: title,
    category_id: catId[slug],
    tags,
    author: 'ডেস্ক রিপোর্ট',
    source_url,
    source: 'admin',
    status: 'published',
    is_featured: i === 0,
    published_at: new Date(now - i * 37 * 60 * 1000).toISOString(),
  });
});

if (!rows.length) {
  console.log('✅ ডেমো খবর আগেই বসানো আছে, নতুন কিছু যোগ হয়নি।');
  process.exit(0);
}
const { error } = await supa.from('posts').insert(rows);
if (error) {
  console.error('❌ খবর বসানো যায়নি:', error.message);
  process.exit(1);
}
console.log(`✅ ${rows.length} টি ডেমো খবর বসানো হয়েছে।`);
